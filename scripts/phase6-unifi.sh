#!/usr/bin/env bash
# Phase 6: UniFi Network Application images. Needs internet.
# The controller is not left running: start it with unifi/unifi-up.sh.
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
need_root
log "Phase 6: UniFi controller"

command -v docker >/dev/null || die "Docker is missing: run scripts/install-docker.sh first"

ENV_FILE=/etc/iot-kit/unifi.env
DATA_DIR=/var/lib/iot-kit/unifi
COMPOSE=(docker compose --env-file "$ENV_FILE" -f "$KIT_DIR/unifi/docker-compose.yml")

if [[ ! -f $ENV_FILE ]]; then
  install -d -m 0750 "$(dirname "$ENV_FILE")"
  (
    umask 077
    cat > "$ENV_FILE" <<EOF
# Generated by phase6-unifi.sh. The database only listens on 127.0.0.1.
MONGO_ROOT_PASS=$(openssl rand -hex 16)
MONGO_PASS=$(openssl rand -hex 16)
UNIFI_DATA=$DATA_DIR
TZ=$TIMEZONE
EOF
  )
  log "created $ENV_FILE"
fi
install -d "$DATA_DIR/db" "$DATA_DIR/config"

"${COMPOSE[@]}" pull

# The Pi 5 kernel uses 16k pages by default, which some MongoDB builds do not
# support. Fail here with a clear message rather than at the workshop.
if ! "${COMPOSE[@]}" run --rm --no-deps --entrypoint mongod unifi-db --version; then
  die "mongod does not run on this kernel (page size $(getconf PAGESIZE)).
    Known fix: add 'kernel=kernel8.img' to /boot/firmware/config.txt (4k pages) and reboot.
    It changes the kernel of the whole Pi: check nothing else depends on 16k pages first."
fi

log "Phase 6 done. Start the controller with: $KIT_DIR/unifi/unifi-up.sh"
