#!/usr/bin/env python3
"""The NeoPixel strip on the Pi: the kit's status panel, plus 8 LEDs anyone
can drive over MQTT. Everything comes from the broker (tools/docker-compose.yml).

    LED 0        power: green, always on while this service runs
    LEDs 1-2     MQTT, both show the same:
                   green flash   a client connected to the broker
                   red flash     a client disconnected
                                 ($SYS/broker/clients/connected, one flash
                                 per client)
                   orange flash  every message on the broker
    LEDs 3-4     WiFi, both show the same:
                   green flash   a device joined (it got a DHCP lease:
                                 dnsmasq hook, bme/s04/net/dhcp)
                   red flash     a device left (presence, bme/s04/net/left)
                 (REVERSE=1 counts all of this from the far end of the strip)
    LEDs 5-12    free: iot-kit/leds/0 ... iot-kit/leds/7 set their colour,
                 iot-kit/leds/all sets the eight at once. Payload: RGB
                 "255,128,0" (also "rgb(255,128,0)") or hex "#ff8000"
                 (also "ff8000", "#f80"). Off is "0,0,0" or "#000000".

The strip is a WS2812 with its data line on GPIO 10 (LED_PIN). A Pi 5 has
no PWM/DMA NeoPixel driver; the bits are generated by the PIO of its RP1
chip, through Adafruit's Adafruit-Blinka-Raspberry-Pi5-Neopixel (needs
/dev/pio0, there on a current Raspberry Pi OS). The strip is only rewritten
when a pixel changed, plus a refresh every few seconds. Without /dev/pio0
the strip is drawn in the log with ANSI colours instead.

Hardware tests, with the service stopped:
    docker compose run --rm leds python3 /leds.py rainbow     (or: solid)
"""
import os
import sys
import time
from collections import deque

import paho.mqtt.client as mqtt

MQTT_HOST = os.environ.get("MQTT_HOST", "localhost")
MQTT_PORT = int(os.environ.get("MQTT_PORT", "1883"))
NET_PREFIX = os.environ.get("NET_PREFIX", "bme/s04/net").strip("/")     # dhcp hook + presence
LED_TOPIC = os.environ.get("LED_TOPIC", "iot-kit/leds").strip("/")      # the free LEDs
BRIGHTNESS = float(os.environ.get("BRIGHTNESS", "0.3"))     # 0..1, keep low on the Pi's 5 V
LED_PIN = int(os.environ.get("LED_PIN", "10"))              # GPIO number of the data line
PIO_DEV = "/dev/pio0"
REFRESH = float(os.environ.get("REFRESH", "5"))             # seconds between rewrites of an unchanged strip (0 = never)
# Topics (prefixes) whose messages do not flash orange, comma separated.
# Empty: every message flashes, the heartbeat of exercise 2 included.
QUIET = tuple(t.strip().strip("/") for t in os.environ.get("QUIET_TOPICS", "").split(",") if t.strip())
FPS = 50

# The layout of the strip. With REVERSE=1 it is counted from the far end:
# the power LED is the last pixel, iot-kit/leds/0 the one next to the WiFi pair.
REVERSE = os.environ.get("REVERSE", "0") == "1"
POWER = 0
MQTT = (1, 2)
WIFI = (3, 4)
FREE = tuple(range(5, 13))          # iot-kit/leds/0..7
N = int(os.environ.get("NUM_PIXELS", str(FREE[-1] + 1)))

OFF, GREEN, RED, ORANGE = (0, 0, 0), (0, 255, 0), (255, 0, 0), (255, 110, 0)
FLASH_ON, FLASH_OFF = 0.25, 0.15    # seconds: a connect / disconnect flash, and the dark gap after it
BLIP = 0.06                         # seconds: the orange flash of one message

def parse_colour(payload: str):
    """RGB '255,128,0' / 'rgb(255, 128, 0)' or hex '#ff8000' / 'ff8000' / '#f80'
    -> (r, g, b); None when it is neither."""
    p = payload.strip().lower()
    h = p.lstrip("#")
    if len(h) == 3 and all(c in "0123456789abcdef" for c in h):
        h = "".join(c * 2 for c in h)
    if len(h) == 6 and all(c in "0123456789abcdef" for c in h):
        return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
    if p.startswith("rgb(") and p.endswith(")"):
        p = p[4:-1]
    parts = [x.strip() for x in p.split(",")]
    if len(parts) == 3 and all(x.isdigit() for x in parts):
        return tuple(min(255, int(x)) for x in parts)
    return None


def dim(colour):
    return tuple(min(255, int(v * BRIGHTNESS)) for v in colour)


# --- the strip ------------------------------------------------------------------

class Pio:
    """WS2812 through the RP1's PIO (Adafruit's driver: real 800 kHz timing,
    any strip length)."""

    def __init__(self, gpio):
        from adafruit_raspberry_pi5_neopixel_write import neopixel_write
        from types import SimpleNamespace
        self.write = neopixel_write
        self.pin = SimpleNamespace(id=gpio)          # the driver only reads pin.id
        self.last = None
        self.t = 0.0

    def show(self, pixels):
        now = time.time()
        if pixels == self.last and (REFRESH <= 0 or now - self.t < REFRESH):
            return
        self.last, self.t = pixels, now
        self.write(self.pin, bytes(v for r, g, b in pixels for v in (g, r, b)))   # WS2812 wants GRB


class Console:
    """Draws the strip in the log, only when it changed."""
    def __init__(self):
        self.last = None

    def show(self, pixels):
        if pixels == self.last:
            return
        self.last = pixels
        sys.stdout.write(time.strftime("%H:%M:%S ") +
                         "".join(f"\033[48;2;{r};{g};{b}m  " for r, g, b in pixels) + "\033[0m\n")
        sys.stdout.flush()


class Both:
    def __init__(self, *outs):
        self.outs = outs

    def show(self, pixels):
        for o in self.outs:
            o.show(pixels)


def open_strip():
    """The strip when there is a PIO; the log otherwise, or as well with
    CONSOLE=1 (to watch the panel without looking at the strip)."""
    outs = []
    if os.path.exists(PIO_DEV):
        try:
            outs.append(Pio(LED_PIN))
            print(f"strip: {N} pixels on GPIO {LED_PIN} ({PIO_DEV})", flush=True)
        except Exception as e:                       # noqa: BLE001
            print(f"strip: cannot use {PIO_DEV} ({e})", flush=True)
    else:
        print(f"strip: no {PIO_DEV}", flush=True)
    if not outs or os.environ.get("CONSOLE") == "1":
        print("strip: drawing in the log", flush=True)
        outs.append(Console())
    return outs[0] if len(outs) == 1 else Both(*outs)


# --- the panel ---------------------------------------------------------------------

class Indicator:
    """A pair of LEDs showing events. Connect / disconnect flashes queue up
    and play one after the other, each followed by a dark gap, so two
    clients joining at once read as two flashes. The orange blip of a
    message only shows when no such flash is playing."""

    def __init__(self):
        self.queue = deque(maxlen=20)   # colours waiting to be flashed
        self.colour = None              # the flash being played
        self.until = 0.0                # ... lit until then
        self.gap_until = 0.0            # ... then dark until then
        self.blip_until = 0.0

    def flash(self, colour, times=1):
        self.queue.extend([colour] * times)

    def blip(self, now):
        self.blip_until = now + BLIP

    def current(self, now):
        if self.colour is not None and now >= self.until:
            self.colour = None
        if self.colour is None and self.queue and now >= self.gap_until:
            self.colour = self.queue.popleft()
            self.until = now + FLASH_ON
            self.gap_until = self.until + FLASH_OFF
        if self.colour is not None:
            return self.colour
        if now < self.gap_until:
            return OFF
        return ORANGE if now < self.blip_until else OFF


class Panel:
    def __init__(self):
        self.wifi = Indicator()
        self.mqtt = Indicator()
        self.free = [OFF] * len(FREE)

    def frame(self, now):
        px = [OFF] * N
        px[POWER] = dim(GREEN)
        w, m = dim(self.wifi.current(now)), dim(self.mqtt.current(now))
        for i in WIFI:
            px[i] = w
        for i in MQTT:
            px[i] = m
        for i, colour in zip(FREE, self.free):
            if i < N:
                px[i] = dim(colour)
        return px[::-1] if REVERSE else px


# --- MQTT -> the panel ----------------------------------------------------------------

def main():
    panel = Panel()
    out = open_strip()
    clients = {"n": None}

    def on_connect(c, userdata, flags, reason_code, properties):
        if reason_code != 0:
            return
        c.subscribe([("#", 0), ("$SYS/broker/clients/connected", 0)])
        print(f"connected to {MQTT_HOST}:{MQTT_PORT}; free LEDs on {LED_TOPIC}/0..{len(FREE) - 1}", flush=True)

    def on_disconnect(c, userdata, flags, reason_code, properties):
        clients["n"] = None
        print("broker lost, reconnecting", flush=True)

    def on_message(c, userdata, msg):
        now = time.time()
        t = msg.topic
        if t == "$SYS/broker/clients/connected":
            n = int(msg.payload or 0)
            if clients["n"] is not None and n != clients["n"]:
                panel.mqtt.flash(GREEN if n > clients["n"] else RED, min(5, abs(n - clients["n"])))
            clients["n"] = n
            return

        topic = t.strip("/")            # "/iot-kit/leds/0" works too
        if topic == f"{NET_PREFIX}/dhcp":
            panel.wifi.flash(GREEN)
        elif topic == f"{NET_PREFIX}/left":
            panel.wifi.flash(RED)
        elif topic.startswith(LED_TOPIC + "/"):
            which = topic[len(LED_TOPIC) + 1:]
            colour = parse_colour(msg.payload.decode("utf-8", "replace"))
            if colour is None:
                print(f"{t}: cannot read {msg.payload[:24]!r}, send 255,128,0 or #ff8000", flush=True)
            elif which == "all":
                panel.free = [colour] * len(FREE)
            elif which.isdigit() and int(which) < len(FREE):
                panel.free[int(which)] = colour
            else:
                print(f"{t}: no such LED (0..{len(FREE) - 1} or all)", flush=True)

        if not (QUIET and topic.startswith(QUIET)):
            panel.mqtt.blip(now)        # every message, this one included

    client = mqtt.Client(mqtt.CallbackAPIVersion.VERSION2, client_id="leds")
    client.on_connect, client.on_disconnect, client.on_message = on_connect, on_disconnect, on_message
    client.reconnect_delay_set(1, 10)
    client.connect_async(MQTT_HOST, MQTT_PORT, keepalive=30)
    client.loop_start()

    period = 1.0 / FPS
    while True:
        t = time.time()
        out.show(panel.frame(t))
        time.sleep(max(0.0, period - (time.time() - t)))


# --- hardware tests -------------------------------------------------------------------

def rainbow():
    """A rainbow turning slowly, no broker involved."""
    import colorsys
    out = open_strip()
    print(f"rainbow on {N} pixels, Ctrl-C to stop", flush=True)
    t0 = time.time()
    while True:
        u = (time.time() - t0) / 6.0                 # one turn every 6 s
        out.show([dim(tuple(int(v * 255) for v in colorsys.hsv_to_rgb((u + i / N) % 1.0, 1.0, 1.0)))
                  for i in range(N)])
        time.sleep(0.05)


def solid():
    """One static frame every 4 s: red, green, blue, white, the first pixel
    only, every other pixel. Tells the colour order and the pixel count."""
    out = open_strip()
    lvl = int(255 * BRIGHTNESS)
    frames = [("all RED", [(lvl, 0, 0)] * N), ("all GREEN", [(0, lvl, 0)] * N),
              ("all BLUE", [(0, 0, lvl)] * N), ("all WHITE", [(lvl, lvl, lvl)] * N),
              ("first pixel WHITE, rest off", [(lvl, lvl, lvl)] + [(0, 0, 0)] * (N - 1)),
              ("every other pixel RED", [(lvl, 0, 0) if i % 2 == 0 else (0, 0, 0) for i in range(N)])]
    while True:
        for name, px in frames:
            print(time.strftime("%H:%M:%S"), name, flush=True)
            out.show(px)
            time.sleep(4)


if __name__ == "__main__":
    {"rainbow": rainbow, "solid": solid}.get(sys.argv[1] if len(sys.argv) > 1 else "", main)()
